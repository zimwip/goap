// RefLink is a reference written as a link: its type, the relative key of its target ("<kind>/<name>") and its
// attributes.
type RefLink struct {
	Type  string
	To    string
	Props map[string]any
}

// RefIndex resolves a name to the relative key of the element of a kind declaring it (the first one when names
// repeat).
type RefIndex map[string]map[string]string // kind -> name -> relative key

// Add declares an element of a kind under a name; the first one declaring a name keeps it.
func (ix RefIndex) Add(kind, name, rel string) {
	if ix[kind] == nil {
		ix[kind] = map[string]string{}
	}
	if _, dup := ix[kind][name]; !dup {
		ix[kind][name] = rel
	}
}

func (ix RefIndex) resolve(kinds []string, name string) (string, bool) {
	for _, k := range kinds {
		if rel, ok := ix[k][name]; ok {
			return rel, true
		}
	}
	return "", false
}

// fieldsOf are the reference fields of a kind of element.
func fieldsOf(kind string) []refField {
	var out []refField
	for _, f := range refFields {
		if slices.Contains(f.kinds, kind) {
			out = append(out, f)
		}
	}
	return out
}

// getField / setField read and write a field (one level of object at most) of the properties of an element.
func getField(p map[string]any, path []string) (any, bool) {
	if len(path) == 1 {
		v, ok := p[path[0]]
		return v, ok
	}
	obj, _ := p[path[0]].(map[string]any)
	v, ok := obj[path[1]]
	return v, ok
}

func setField(p map[string]any, path []string, v any) {
	if len(path) == 1 {
		if v == nil {
			delete(p, path[0])
		} else {
			p[path[0]] = v
		}
		return
	}
	obj, _ := p[path[0]].(map[string]any)
	obj = maps.Clone(obj)
	if v == nil {
		delete(obj, path[1])
	} else {
		if obj == nil {
			obj = map[string]any{}
		}
		obj[path[1]] = v
	}
	if len(obj) == 0 {
		delete(p, path[0])
	} else {
		p[path[0]] = obj
	}
}

// Encoded is what EncodeRefs makes of the properties of an element: the properties left (the names that resolved
// cut out) and the links.
type Encoded struct {
	Props map[string]any
	Links []RefLink
}

// EncodeRefs cuts the references of an element (kind, props) that resolve to an element of the version out of its
// properties and returns them as links.
func EncodeRefs(kind string, props map[string]any, ix RefIndex) Encoded {
	out := Encoded{Props: maps.Clone(props)}
	for _, f := range fieldsOf(kind) {
		v, ok := getField(out.Props, f.path)
		if !ok || v == nil {
			continue
		}
		attrs := func(extra map[string]any) map[string]any {
			p := maps.Clone(extra)
			if f.as != "" {
				if p == nil {
					p = map[string]any{}
				}
				p[LinkAttrAs] = f.as
			}
			return p
		}
		switch f.shape {
		case refOne:
			name, _ := v.(string)
			if rel, ok := ix.resolve(f.to, name); ok {
				out.Links = append(out.Links, RefLink{f.link, rel, attrs(nil)})
				setField(out.Props, f.path, nil)
			}
		case refList:
			list, _ := v.([]any)
			var rest []any
			for i, item := range list {
				name, _ := item.(string)
				if rel, ok := ix.resolve(f.to, name); ok {
					out.Links = append(out.Links, RefLink{f.link, rel, attrs(map[string]any{LinkAttrPosition: float64(i)})})
				} else {
					rest = append(rest, item)
				}
			}
			if rest == nil {
				setField(out.Props, f.path, nil)
			} else {
				setField(out.Props, f.path, rest)
			}
		case refMap:
			m, _ := v.(map[string]any)
			rest := map[string]any{}
			for _, name := range slices.Sorted(maps.Keys(m)) {
				if rel, ok := ix.resolve(f.to, name); ok {
					out.Links = append(out.Links, RefLink{f.link, rel, attrs(map[string]any{LinkAttrValue: m[name]})})
				} else {
					rest[name] = m[name]
				}
			}
			if len(rest) == 0 && len(m) > 0 {
				setField(out.Props, f.path, nil)
			} else {
				setField(out.Props, f.path, rest)
			}
		}
	}
	return out
}

// RefTarget is a reference link read back: its type, its attributes and the kind and name of its target.
type RefTarget struct {
	Type       string
	Props      map[string]any
	Kind, Name string
}

// DecodeRefs puts the references an element's links carry back into its properties.
func DecodeRefs(kind string, props map[string]any, links []RefTarget) map[string]any {
	out := maps.Clone(props)
	type listItem struct {
		pos  float64
		name string
	}
	lists := map[int][]listItem{}
	fields := fieldsOf(kind)
	for _, l := range links {
		as, _ := l.Props[LinkAttrAs].(string)
	field:
		for i, f := range fields {
			if f.link != l.Type || f.as != as || !slices.Contains(f.to, l.Kind) {
				continue
			}
			switch f.shape {
			case refOne:
				setField(out, f.path, l.Name)
			case refList:
				pos, _ := l.Props[LinkAttrPosition].(float64)
				lists[i] = append(lists[i], listItem{pos, l.Name})
			case refMap:
				v, ok := getField(out, f.path)
				m, _ := v.(map[string]any)
				if !ok || m == nil {
					m = map[string]any{}
				} else {
					m = maps.Clone(m)
				}
				val, ok := l.Props[LinkAttrValue]
				if !ok {
					val = true
				}
				m[l.Name] = val
				setField(out, f.path, m)
			}
			break field
		}
	}
	for i, items := range lists {
		f := fields[i]
		sort.SliceStable(items, func(a, b int) bool { return items[a].pos < items[b].pos })
		// the names that stayed in the property (unresolved) take the places the linked ones leave free
		var rest []any
		if v, ok := getField(out, f.path); ok {
			rest, _ = v.([]any)
		}
		names := make([]any, len(items)+len(rest))
		taken := make([]bool, len(names))
		var late []string
		for _, it := range items {
			if p := int(it.pos); p >= 0 && p < len(names) && !taken[p] {
				names[p], taken[p] = it.name, true
			} else {
				late = append(late, it.name)
			}
		}
		free := 0
		place := func(v any) {
			for taken[free] {
				free++
			}
			names[free], taken[free] = v, true
		}
		for _, v := range rest {
			place(v)
		}
		for _, n := range late {
			place(n)
		}
		setField(out, f.path, names)
	}
	return out
}

// conditionRE finds the conditions a CEL expression reads (conditions.x, self.conditions.x).
var conditionRE = regexp.MustCompile(`\bconditions\.([A-Za-z_][A-Za-z0-9_]*)`)

// DerivedRefs are the references of an element the definition keeps in its own words, so that they are never read
// back from the graph (ADR 0120): the conditions its expressions read (where, expr, when, filters: mentions) or a
// nested structure of it names (the conditions of an assessment state, the until of a persistent agent), the roles and
// goals of its triggers (assigns and pursues, as trigger). A link carrying an "as" no field of the kind has, or a type
// no field reads, is never decoded.
func DerivedRefs(kind string, props map[string]any, ix RefIndex, self string) []RefLink {
	var out []RefLink
	seen := map[string]bool{}
	add := func(typ, rel, as string) {
		k := typ + " " + rel + " " + as
		if rel == self || seen[k] {
			return
		}
		seen[k] = true
		var p map[string]any
		if as != "" {
			p = map[string]any{LinkAttrAs: as}
		}
		out = append(out, RefLink{typ, rel, p})
	}
	mention := func(name string) {
		if rel, ok := ix.resolve([]string{ElementCondition}, name); ok {
			add(LinkMentions, rel, "")
		}
	}
	var walk func(key string, v any)
	walk = func(key string, v any) {
		switch x := v.(type) {
		case string:
			for _, m := range conditionRE.FindAllStringSubmatch(x, -1) {
				mention(m[1])
			}
		case []any:
			for _, it := range x {
				walk(key, it)
			}
		case map[string]any:
			for _, k := range slices.Sorted(maps.Keys(x)) {
				if key == "conditions" || key == "until" {
					mention(k)
				}
				walk(k, x[k])
			}
		}
	}
	for _, k := range slices.Sorted(maps.Keys(props)) {
		walk(k, props[k])
	}
	if kind == ElementAgent {
		triggers, _ := props["triggers"].([]any)
		for _, t := range triggers {
			tm, _ := t.(map[string]any)
			roles, _ := tm["roles"].([]any)
			for _, r := range roles {
				name, _ := r.(string)
				if rel, ok := ix.resolve([]string{ElementRole}, name); ok {
					add(LinkAssigns, rel, "trigger")
				}
			}
			if goal, _ := tm["goal"].(string); goal != "" {
				if rel, ok := ix.resolve([]string{ElementGoal}, goal); ok {
					add(LinkPursues, rel, "trigger")
				}
			}
		}
	}
	return out
}

// RefKind is what tells a reference field from the others on a link: its link type and its "as".
type RefKind struct{ Type, As string }

// RefKindsOf are the link types (and "as") of the reference fields of an element of a kind that props carries: the
// links an edit of those fields replaces.
func RefKindsOf(kind string, props map[string]any) []RefKind {
	var out []RefKind
	for _, f := range fieldsOf(kind) {
		if _, ok := props[f.path[0]]; ok {
			out = append(out, RefKind{f.link, f.as})
		}
	}
	return out
}

// RefIndexOf indexes the declared elements of a methodology (not its steps) by kind and name, each under its relative
// key "<kind>/<name>".
func RefIndexOf(m *Methodology) RefIndex {
	ix := RefIndex{}
	add := func(kind, name string) { ix.Add(kind, name, kind+"/"+name) }
	for _, c := range m.Conditions {
		add(ElementCondition, c.Name)
	}
	for _, a := range m.Actions {
		add(ElementAction, a.Name)
	}
	for _, g := range m.Goals {
		add(ElementGoal, g.Name)
	}
	for _, a := range m.Agents {
		add(ElementAgent, a.Name)
	}
	for _, p := range m.Processes {
		add(ElementProcess, p.Name)
	}
	for _, x := range m.Methods {
		add(ElementMethod, x.Name)
	}
	for _, r := range m.Roles {
		add(ElementRole, r.Name)
	}
	return ix
}

// elementTypes are the node types of the elements (built-in meta-domain methodology).
var elementTypes = map[string]string{
	"methodology@Condition": ElementCondition, "methodology@Action": ElementAction, "methodology@Goal": ElementGoal,
	"methodology@Agent": ElementAgent, "methodology@Process": ElementProcess, "methodology@Method": ElementMethod,
	"methodology@Role": ElementRole, "methodology@Step": ElementStep, "methodology@MethodStep": ElementMethodStep,
	"methodology@MethodologyVersion": ElementVersion,
}

// ElementOfType is the kind of element a node of the type is ("" for none).
func ElementOfType(typ string) string { return elementTypes[typ] }
