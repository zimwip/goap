// References between the elements of a methodology version are links of the graph, not names in properties (ADR
// 0119): a condition an action or a step needs is a `requires` link to the condition node, one it establishes a
// `produces` link, so that the same condition node is the output of an activity and the input of another. The
// definition (YAML, the registry API) keeps naming its elements; the store cuts the names it resolves to an element of
// the version out of the properties and writes them as links (EncodeRefs), and puts them back when it reads the
// version (DecodeRefs). A name that resolves to no element of the version (a condition of a library or generated by
// the platform, "state:x", "step:p/s"; an element of another methodology, "m/x"; a name a draft does not declare yet)
// stays in the property: it has no node to link to.

// Link types of the references (built-in meta-domain methodology, domains/builtin/methodology.yaml).
const (
	LinkRequires     = "methodology@requires"       // an input: a condition an activity or a goal needs
	LinkProduces     = "methodology@produces"       // an output: a condition an activity establishes
	LinkUses         = "methodology@uses"           // the actions an agent plans over, the pool of a method
	LinkPursues      = "methodology@pursues"        // the goals of an agent
	LinkPerformedBy  = "methodology@performed_by"   // the action a step runs, or its alternatives
	LinkNests        = "methodology@nests"          // the process a step nests
	LinkCarriedOutBy = "methodology@carried_out_by" // the methods providing the capability a step names
	LinkAssigns      = "methodology@assigns"        // a role: allowed to run, acted as, or RACI
	LinkAggregates   = "methodology@aggregates"     // the scoped condition an aggregate condition is over
	LinkSpecializes  = "methodology@specializes"    // the action a specialization specializes
	LinkMainGoal     = "methodology@main_goal"      // the main goal of a version (a goal or a process)
	LinkMentions     = "methodology@mentions"       // a condition an expression or a nested structure of an element reads
)

// Attributes of the reference links.
const (
	LinkAttrValue    = "value"    // a map reference: the value the condition is required or established with
	LinkAttrPosition = "position" // a list reference: its position in the list
	LinkAttrAs       = "as"       // what the reference is, when a link type carries several fields of a kind
)

// Kinds of the elements of a definition, as the store keys their nodes ("<version key>/<kind>/<name>").
const (
	ElementCondition  = "condition"
	ElementAction     = "action"
	ElementGoal       = "goal"
	ElementAgent      = "agent"
	ElementProcess    = "process"
	ElementMethod     = "method"
	ElementRole       = "role"
	ElementStep       = "step"       // a step of a process, keyed by its path
	ElementMethodStep = "methodStep" // a step of a method
	// ElementVersion stands for the header of the version (the MethodologyVersion node).
	ElementVersion = "version"
)

// Shapes of a reference field.
const (
	refOne  = iota // a name
	refList        // a list of names
	refMap         // names to a boolean (a condition and its value)
)

// refField is a field of an element naming other elements of the version.
type refField struct {
	kinds []string // kinds of the elements carrying it
	path  []string // the field, or an object field and its key ("roles", "responsible")
	shape int
	link  string
	as    string   // the value of the link's "as" attribute, telling fields of one link type apart ("" none)
	to    []string // kinds of the target, the first declaring the name wins
}

