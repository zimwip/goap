<#
.SYNOPSIS
  Windows equivalent of the Makefile (PowerShell 5.1+ ships with Windows, no `make` needed): the same targets, doing the
  same things. Keep the two in step.

.EXAMPLE
  .\make.cmd test
  .\make.ps1 dev
  .\make.ps1 help
#>
param(
    [Parameter(Position = 0)][string]$Target = 'help'
)

$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$Services = 'graph', 'registry', 'engine', 'modelgw', 'preferences', 'conversations', 'credentials', 'indexer', 'events', 'gateway', 'mcp', 'connector-localfs', 'connector-workspace', 'connector-claude-coding-agent', 'goap-dev', 'goap-runner', 'goap-eval', 'goap-bench'
# the modules of the go.work (ADR 0125): `./...` at the root matches none, every Go command names them
$Modules = 'contracts', 'lib', 'graph', 'engine', 'mcp', 'gateway', 'platform'
$Pkgs = $Modules | ForEach-Object { "./$_/..." }
$Compose = @('compose', '-f', 'deploy/compose/docker-compose.yml')
$Exe = if ($env:OS -eq 'Windows_NT') { '.exe' } else { '' }

# generators installed by `tools` live in GOPATH/bin
$gobin = Join-Path (& go env GOPATH) 'bin'
$env:PATH = "$env:PATH$([IO.Path]::PathSeparator)$gobin"

# Run a native command and stop on a non-zero exit code.
function Run {
    $cmd, $rest = $args
    & $cmd @rest
    if ($LASTEXITCODE -ne 0) { throw "$cmd $($rest -join ' ') failed (exit $LASTEXITCODE)" }
}

# Run a block in a directory, coming back whatever happens.
function InDir($dir, [scriptblock]$block) {
    Push-Location $dir
    try { & $block }
    finally { Pop-Location }
}

function Tools {
    Run go install github.com/bufbuild/buf/cmd/buf@latest
    Run go install google.golang.org/protobuf/cmd/protoc-gen-go@latest
    Run go install connectrpc.com/connect/cmd/protoc-gen-connect-go@latest
    Run go install github.com/air-verse/air@latest
}

function Generate {
    # the web's TypeScript (web/src/gen) is generated by protoc-gen-es, a dev dependency of the web
    if (-not (Test-Path web/node_modules/@bufbuild/protoc-gen-es)) { InDir web { Run npm ci --ignore-scripts } }
    Run buf lint
    Run buf generate
    Run go generate ./contracts/operations/
}

function Build {
    New-Item -ItemType Directory -Force bin | Out-Null
    foreach ($s in $Services) { Run go build -o "bin/$s$Exe" "./platform/cmd/$s" }
}

function Test { Run go test @Pkgs }

# every test with the scripts run by the wasm JavaScript engine (ADR 0134)
function TestWasm {
    $prev = $env:GOAP_JS_ENGINE
    $env:GOAP_JS_ENGINE = 'wasm'
    try { Run go test -count=1 @Pkgs } finally { $env:GOAP_JS_ENGINE = $prev }
}

function Tidy { foreach ($m in $Modules) { InDir $m { Run go mod tidy } } }

function WebTest { InDir web { Run npm test } }

# every test, the PostgreSQL ones included: GOAP_TEST_PG_DSN, else a throw-away pgvector container on PGTEST_PORT
function TestPg {
    if ($env:GOAP_TEST_PG_DSN) { Run go test -count=1 @Pkgs; return }
    $image = if ($env:PGTEST_IMAGE) { $env:PGTEST_IMAGE } else { 'pgvector/pgvector:pg17' }
    $port = if ($env:PGTEST_PORT) { $env:PGTEST_PORT } else { '55432' }
    $c = & docker run -d --rm -e POSTGRES_USER=goap -e POSTGRES_PASSWORD=goap -e POSTGRES_DB=goap -p "${port}:5432" $image
    if ($LASTEXITCODE -ne 0) { throw "docker run $image failed (exit $LASTEXITCODE)" }
    try {
        # the server starts twice (init, then for real): wait for the second "ready"; docker logs writes to stderr
        while (@(& { $ErrorActionPreference = 'Continue'; & docker logs $c 2>&1 } | Select-String 'ready to accept connections').Count -lt 2) {
            Start-Sleep -Seconds 1
        }
        $env:GOAP_TEST_PG_DSN = "postgres://goap:goap@localhost:$port/goap?sslmode=disable"
        try { Run go test -count=1 @Pkgs }
        finally { Remove-Item Env:GOAP_TEST_PG_DSN -ErrorAction SilentlyContinue }
    }
    finally { & docker stop $c | Out-Null }
}

# offline evaluation of LLM work (ADR 0099) against a running goap-dev or gateway: GOAP_TOKEN, GOAP_EVAL_URL, EVAL (cases)
function Eval {
    $cases = if ($env:EVAL) { $env:EVAL } else { 'evals' }
    Run go run ./platform/cmd/goap-eval $cases
}

function Lint {
    Run go vet @Pkgs
    $unformatted = & gofmt -l @Modules | Where-Object { $_ }
    if ($unformatted) {
        $unformatted | ForEach-Object { Write-Host $_ }
        throw 'gofmt: files above are not formatted'
    }
    $a = (Get-FileHash docs/dsl.md).Hash
    $b = (Get-FileHash web/src/lib/help/dsl.md).Hash
    if ($a -ne $b) { throw 'web/src/lib/help/dsl.md is out of sync with docs/dsl.md' }
    foreach ($m in $Modules) {
        InDir $m { & go mod tidy -diff *> $null; if ($LASTEXITCODE -ne 0) { throw "$m/go.mod is not tidy: .\make.ps1 tidy" } }
    }
}

# SQLite backend only, rebuilt and restarted by air on .go changes: http://localhost:8080. .air.toml is written for a
# POSIX shell (an environment prefix, a binary with no extension): its build settings are given on the command line here.
function DevBackend {
    if (-not (Get-Command air -ErrorAction SilentlyContinue)) { Run go install github.com/air-verse/air@latest }
    $bin = ".air/goap-dev$Exe"
    $old = $env:GOAP_STORE
    $env:GOAP_STORE = 'sqlite'
    try { Run air -c .air.toml --build.cmd "go build -o $bin ./platform/cmd/goap-dev" --build.entrypoint $bin --build.full_bin $bin }
    finally { $env:GOAP_STORE = $old }
}

# IDE only, hot-reloaded by vite, proxied to the backend: http://localhost:5173
function DevWeb {
    InDir web {
        Run npm install --no-audit --no-fund
        Run npm run dev
    }
}

# on this machine, no docker: SQLite (.goap/goap.db), backend + IDE both reload on code change: http://localhost:5173
function Dev {
    $shell = (Get-Process -Id $PID).Path # powershell.exe or pwsh, whichever runs this script
    $backend = Start-Process -FilePath $shell -NoNewWindow -PassThru -ArgumentList @(
        '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', (Join-Path $PSScriptRoot 'make.ps1'), 'dev-backend')
    try { DevWeb }
    finally {
        # the backend and what it started (air, goap-dev)
        if ($env:OS -eq 'Windows_NT') { & taskkill /T /F /PID $backend.Id 2>&1 | Out-Null }
        else { Stop-Process -Id $backend.Id -Force -ErrorAction SilentlyContinue }
    }
}

function DevReset { Remove-Item -Recurse -Force .goap -ErrorAction SilentlyContinue }

function RunnerImage { Run docker build --build-arg SERVICE=goap-runner -t goap/runner:dev . }

function Images { RunnerImage; Run docker build --target services -t goap/goap:dev . }

function ClaudeAgentRunner { Run go run ./platform/cmd/connector-claude-coding-agent install }

# Engine socket for the docker-proxy service: Docker Desktop keeps it in its VM, at the default path
function DockerSock { if (-not $env:GOAP_DOCKER_SOCK) { $env:GOAP_DOCKER_SOCK = '/var/run/docker.sock' } }

function Up {
    Images
    DockerSock
    Run docker @Compose up -d
    Urls
}

function Urls { Get-Content deploy/compose/urls.txt | Write-Host }

function Down { DockerSock; Run docker @Compose down }
function Reset {
    DockerSock
    Run docker @Compose down --volumes --remove-orphans
    & docker image rm goap/goap:dev goap/runner:dev # absent images are not an error
}
# Performance stack (deploy/compose/perf.yml): the graph service on PostgreSQL, goap-bench, Prometheus and Grafana
$Perf = @('compose', '-f', 'deploy/compose/perf.yml')
function PerfArgs { if ($env:PERF_ARGS) { -split $env:PERF_ARGS } else { @('-versions', '100000') } }
# goap-bench stays up once its run ends, so its series stay in Grafana, until interrupted; $env:PERF_AUTOSTOP = '30m'
# stops it after that long, '0' with the run
function PerfHold { if ($env:PERF_AUTOSTOP) { "-hold=$env:PERF_AUTOSTOP" } else { '-hold=-1s' } }
function PerfUp { Run docker build --target services -t goap/goap:dev .; Run docker @Perf up -d }
function PerfRun { $a = PerfArgs; $h = PerfHold; Run docker @Perf run --rm bench $h @a }
# captures of the performance stack's Prometheus (perf-capture), replayed by perf-analysis
$PerfCaptures = '.goap/perf/captures'
$PerfAnalysis = @('compose', '-f', 'deploy/compose/perf-analysis.yml')
function PerfCapture {
    $name = if ($env:PERF_CAPTURE) { $env:PERF_CAPTURE } else { Get-Date -Format 'yyyyMMdd-HHmmss' }
    $dir = Join-Path $PerfCaptures $name
    if (Test-Path $dir) { throw "perf-capture: $dir exists" }
    $metrics = & docker @Perf exec -T prometheus wget -qO- http://localhost:9090/metrics
    $line = $metrics | Where-Object { $_ -match '^prometheus_tsdb_lowest_timestamp_seconds ' } | Select-Object -First 1
    $from = if ($line) { [int64][double]($line -split ' ')[1] * 1000 } else { 0 }
    $answer = & docker @Perf exec -T prometheus wget -qO- --post-data= http://localhost:9090/api/v1/admin/tsdb/snapshot
    $snap = if ($answer) { ($answer | ConvertFrom-Json).data.name } else { $null }
    if (-not $snap) { throw 'perf-capture: Prometheus took no snapshot (perf-up first)' }
    New-Item -ItemType Directory -Force -Path $PerfCaptures | Out-Null
    Run docker @Perf cp "prometheus:/prometheus/snapshots/$snap" $dir
    Run docker @Perf exec -T prometheus rm -rf "/prometheus/snapshots/$snap"
    $to = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds()
    Set-Content -Path (Join-Path $dir 'range') -Value "$from $to" -NoNewline
    Write-Host "captured ${dir}: `$env:PERF_CAPTURE = '$name'; .\make.ps1 perf-analysis"
}
function PerfAnalysis {
    $name = $env:PERF_CAPTURE
    if (-not $name -and (Test-Path $PerfCaptures)) { $name = (Get-ChildItem -Directory $PerfCaptures | Sort-Object Name | Select-Object -Last 1).Name }
    if (-not $name -or -not (Test-Path (Join-Path $PerfCaptures $name))) { throw "perf-analysis: no capture $name in $PerfCaptures (perf-capture)" }
    $dir = Join-Path $PerfCaptures $name
    $env:GOAP_PERF_CAPTURE = (Resolve-Path $dir).Path
    try { Run docker @PerfAnalysis up -d --force-recreate } finally { Remove-Item Env:GOAP_PERF_CAPTURE }
    $from, $to = (Get-Content (Join-Path $dir 'range') -Raw).Trim() -split ' '
    Write-Host "Grafana: http://localhost:3301/d/goap-perf?from=$from&to=$to - Prometheus: http://localhost:9391 - .\make.ps1 perf-analysis-down to stop"
}
function PerfAnalysisDown { $env:GOAP_PERF_CAPTURE = '.'; try { Run docker @PerfAnalysis down } finally { Remove-Item Env:GOAP_PERF_CAPTURE } }
function Perf {
    PerfUp
    PerfRun
    Write-Host 'Grafana: http://localhost:3300/d/goap-perf - Prometheus: http://localhost:9390 - web: http://localhost:5174 - reports: .goap\perf\*.csv'
}
function PerfDown { Run docker @Perf --profile bench down }
function PerfReset { Run docker @Perf --profile bench down --volumes --remove-orphans }

function Logs { DockerSock; Run docker @Compose logs -f engine graph registry modelgw gateway }

function Help {
    @'
Usage: .\make.ps1 <target>   (or .\make.cmd <target>)

  all               generate, build, test
  tools             install code generators (and air)
  generate          regenerate connect-rpc code and the web's TypeScript (web/src/gen) from proto/,
                    and the catalogue of operations
  build             build all services into bin\
  test              go test of every module of the go.work
  test-wasm         every go test with the scripts run by the wasm JavaScript engine (GOAP_JS_ENGINE=wasm)
  tidy              go mod tidy in every module
  web-test          unit tests of the web (needs npm install in web\)
  test-pg           every test, the PostgreSQL ones included (GOAP_TEST_PG_DSN, else a throw-away
                    pgvector container on PGTEST_PORT, 55432)
  lint              go vet + gofmt + dsl.md sync check + go.mod files tidy
  eval              offline evaluation cases of evals\ (or $env:EVAL) against a running gateway, as GOAP_TOKEN
  dev               no docker: SQLite (.goap\goap.db), backend + IDE both reload on code change:
                    http://localhost:5173
  dev-backend       SQLite backend only, rebuilt and restarted by air: http://localhost:8080
  dev-web           IDE only, hot-reloaded by vite, proxied to the backend: http://localhost:5173
  dev-reset         drop the local SQLite database
  web               same as dev-web
  runner-image      image of the script sandboxes (goap-runner)
  images            the image of every Go service of the compose stack (goap/goap:dev), built once
  claude-agent-runner  install the Claude Agent SDK of the claude-coding-agent connector
                    (GOAP_CLAUDE_AGENT_DIR, default .goap\claude-agent; needs npm)
  up | down | logs  docker compose stack (up prints its URLs and how to reach its database, DBeaver)
  reset             stop the stack and drop its containers, volumes (database, NATS, web modules) and images
  urls              the URLs of the compose stack: IDE, gateway, each service, tools, database
  perf              performance test in docker: the graph service on PostgreSQL loaded by goap-bench
                    ($env:PERF_ARGS, goap-bench -h), measured in Grafana http://localhost:3300; goap-bench holds
                    once its run ends until interrupted, or for $env:PERF_AUTOSTOP (e.g. 30m; 0: exits with the run)
  perf-up | perf-run | perf-down | perf-reset
                    start the performance stack, one more run of goap-bench, stop it (keeping its data), drop its data
  perf-capture      save what the performance stack's Prometheus holds in .goap\perf\captures\<$env:PERF_CAPTURE>
  perf-analysis | perf-analysis-down
                    replay a capture ($env:PERF_CAPTURE, default the latest) in a Grafana of its own,
                    http://localhost:3301, with no graph nor bench; stop it
'@ | Write-Host
}

