<#
.SYNOPSIS
  Windows equivalent of the Makefile (PowerShell 5.1+ ships with Windows, no `make` needed): the same targets, doing the
  same things. Keep the two in step.

.EXAMPLE
  .\make.cmd test
  .\make.ps1 devlocal
  .\make.ps1 help
#>
param(
    [Parameter(Position = 0)][string]$Target = 'help'
)

$ErrorActionPreference = 'Stop'
Set-Location $PSScriptRoot

$Services = 'graph', 'registry', 'engine', 'modelgw', 'preferences', 'conversations', 'credentials', 'indexer', 'events', 'gateway', 'mcp', 'connector-localfs', 'connector-workspace', 'connector-claude-coding-agent', 'goap-dev', 'goap-runner', 'goap-eval'
# extra arguments of the workspace commands, e.g. $env:CARGO_EXCLUDE = '--exclude goap-e2e-engine'
$Exclude = if ($env:CARGO_EXCLUDE) { -split $env:CARGO_EXCLUDE } else { @() }
# buf lints the protos and writes the web's TypeScript (web/src/gen); the one on the PATH, else the npm package
$BufVersion = if ($env:BUF_VERSION) { $env:BUF_VERSION } else { '1.50.0' }
$Compose = @('compose', '-f', 'deploy/compose/docker-compose.yml')
$Exe = if ($env:OS -eq 'Windows_NT') { '.exe' } else { '' }

# rustup installs cargo (and `cargo install` the tools) in ~/.cargo/bin
$cargobin = Join-Path $HOME '.cargo/bin'
if (Test-Path $cargobin) { $env:PATH = "$env:PATH$([IO.Path]::PathSeparator)$cargobin" }

# Run a native command and stop on a non-zero exit code.
function Run {
    $cmd, $rest = $args
    & $cmd @rest
    if ($LASTEXITCODE -ne 0) { throw "$cmd $($rest -join ' ') failed (exit $LASTEXITCODE)" }
}

# Run a block in a directory, coming back whatever happens.
function InDir($dir, [scriptblock]$block) {
    Push-Location $dir
    try { & $block }
    finally { Pop-Location }
}

# Install what building needs when it is missing: rustup + the toolchain pinned by rust-toolchain.toml; checks node.
function Toolchain {
    if (-not (Get-Command rustup -ErrorAction SilentlyContinue)) {
        Write-Host 'rustup not found: installing it (https://rustup.rs)'
        if ($env:OS -eq 'Windows_NT') {
            $installer = Join-Path ([IO.Path]::GetTempPath()) 'rustup-init.exe'
            $arch = if ($env:PROCESSOR_ARCHITECTURE -eq 'ARM64') { 'aarch64' } else { 'x86_64' }
            Invoke-WebRequest -UseBasicParsing "https://static.rust-lang.org/rustup/dist/$arch-pc-windows-msvc/rustup-init.exe" -OutFile $installer
            Run $installer -y --profile minimal --default-toolchain none
        } else {
            $script = Join-Path ([IO.Path]::GetTempPath()) 'rustup-init.sh'
            Invoke-WebRequest -UseBasicParsing 'https://sh.rustup.rs' -OutFile $script
            Run sh $script -y --profile minimal --default-toolchain none
        }
        $env:PATH = "$env:PATH$([IO.Path]::PathSeparator)$cargobin"
    }
    & rustup show active-toolchain *> $null
    if ($LASTEXITCODE -ne 0) { Run rustup toolchain install }
    Run rustup show active-toolchain
    if ($env:OS -eq 'Windows_NT' -and -not (Get-Command link.exe -ErrorAction SilentlyContinue) -and -not (Test-Path "${env:ProgramFiles(x86)}\Microsoft Visual Studio\Installer\vswhere.exe")) {
        Write-Warning 'the MSVC linker was not found: install the Visual Studio Build Tools (C++ workload), e.g. winget install Microsoft.VisualStudio.2022.BuildTools'
    }
    if (-not (Get-Command node -ErrorAction SilentlyContinue)) { Write-Warning 'node / npm not found, needed for the web (web\) and generate: https://nodejs.org' }
}

# watchexec rebuilds and restarts the backend of devlocal on a change: installed when it is missing
function WatchTool {
    Toolchain
    if (-not (Get-Command watchexec -ErrorAction SilentlyContinue)) { Run cargo install --locked watchexec-cli }
}

# buf on the PATH, else the npm package
function Buf {
    if (Get-Command buf -ErrorAction SilentlyContinue) { Run buf @args }
    else { Run npx --yes "@bufbuild/buf@$BufVersion" @args }
}

function Tools {
    WatchTool
    if (-not (Get-Command buf -ErrorAction SilentlyContinue)) { Run npm install -g "@bufbuild/buf@$BufVersion" }
}

function Generate {
    Toolchain
    # the web's TypeScript (web/src/gen) is generated by protoc-gen-es, a dev dependency of the web
    if (-not (Test-Path web/node_modules/@bufbuild/protoc-gen-es)) { InDir web { Run npm ci --ignore-scripts } }
    Buf lint
    Buf generate
    # the catalogue of operations (contracts/operations) and the form widget catalogue of the web
    $env:GOAP_UPDATE_OPERATIONS = '1'
    try { Run cargo test -p goap-opgen --lib catalogue_is_current }
    finally { Remove-Item Env:GOAP_UPDATE_OPERATIONS -ErrorAction SilentlyContinue }
    $env:GOAP_UPDATE_WEB = '1'
    try { Run cargo test -p goap-form --test catalog }
    finally { Remove-Item Env:GOAP_UPDATE_WEB -ErrorAction SilentlyContinue }
}

function Build {
    Toolchain
    Run cargo build --workspace @Exclude
    New-Item -ItemType Directory -Force bin | Out-Null
    foreach ($s in $Services) { Copy-Item -Force "target/debug/$s$Exe" "bin/$s$Exe" }
}

function Test { Toolchain; Run cargo test --workspace @Exclude }

# bring Cargo.lock in line with the manifests of the workspace
function Tidy { Toolchain; Run cargo update --workspace }

function WebTest { InDir web { Run npm test } }

# every test, the PostgreSQL ones included: GOAP_TEST_PG_DSN, else a throw-away pgvector container on PGTEST_PORT
function TestPg {
    Toolchain
    if ($env:GOAP_TEST_PG_DSN) { Run cargo test --workspace @Exclude; return }
    $image = if ($env:PGTEST_IMAGE) { $env:PGTEST_IMAGE } else { 'pgvector/pgvector:pg17' }
    $port = if ($env:PGTEST_PORT) { $env:PGTEST_PORT } else { '55432' }
    $c = & docker run -d --rm -e POSTGRES_USER=goap -e POSTGRES_PASSWORD=goap -e POSTGRES_DB=goap -p "${port}:5432" $image
    if ($LASTEXITCODE -ne 0) { throw "docker run $image failed (exit $LASTEXITCODE)" }
    try {
        # the server starts twice (init, then for real): wait for the second "ready"; docker logs writes to stderr
        while (@(& { $ErrorActionPreference = 'Continue'; & docker logs $c 2>&1 } | Select-String 'ready to accept connections').Count -lt 2) {
            Start-Sleep -Seconds 1
        }
        $env:GOAP_TEST_PG_DSN = "postgres://goap:goap@localhost:$port/goap?sslmode=disable"
        try { Run cargo test --workspace @Exclude }
        finally { Remove-Item Env:GOAP_TEST_PG_DSN -ErrorAction SilentlyContinue }
    }
    finally { & docker stop $c | Out-Null }
}

# offline evaluation of LLM work (ADR 0099) against a running goap-dev or gateway: GOAP_TOKEN, GOAP_EVAL_URL, EVAL (cases)
function Eval {
    $cases = if ($env:EVAL) { $env:EVAL } else { 'evals' }
    Toolchain
    Run cargo run -q -p goap-cmd-goap-eval -- $cases
}

# rustfmt + clippy (warnings refused) + Cargo.lock in line with the manifests + dsl.md sync check
function Lint {
    Toolchain
    Run cargo fmt --all --check
    Run cargo clippy --workspace @Exclude --all-targets -- -D warnings
    & cargo metadata --locked --format-version 1 *> $null
    if ($LASTEXITCODE -ne 0) { throw 'Cargo.lock is not in line with the manifests: .\make.ps1 tidy' }
    $a = (Get-FileHash docs/dsl.md).Hash
    $b = (Get-FileHash web/src/lib/help/dsl.md).Hash
    if ($a -ne $b) { throw 'web/src/lib/help/dsl.md is out of sync with docs/dsl.md' }
}

function Dev { Toolchain; Run cargo run -p goap-cmd-goap-dev }

# SQLite backend only, rebuilt and restarted by watchexec on source changes (the crates, the protos, the manifests; not
# web/, .goap/, target/, deploy/): http://localhost:8080
function DevLocalBackend {
    WatchTool
    $watch = 'contracts', 'lib', 'graph', 'engine', 'mcp', 'gateway', 'platform', 'proto', 'Cargo.toml', 'Cargo.lock' |
        ForEach-Object { '-w', $_ }
    $old = $env:GOAP_STORE
    $env:GOAP_STORE = 'sqlite'
    try { Run watchexec -r @watch -e 'rs,toml,lock,sql,proto,yaml,mjs,json' -- cargo run -p goap-cmd-goap-dev }
    finally { $env:GOAP_STORE = $old }
}

# IDE only, hot-reloaded by vite, proxied to the backend: http://localhost:5173
function DevLocalWeb {
    InDir web {
        Run npm install --no-audit --no-fund
        Run npm run dev
    }
}

# on this machine, no docker: SQLite (.goap/goap.db), backend + IDE both reload on code change: http://localhost:5173
function DevLocal {
    WatchTool
    $shell = (Get-Process -Id $PID).Path # powershell.exe or pwsh, whichever runs this script
    $backend = Start-Process -FilePath $shell -NoNewWindow -PassThru -ArgumentList @(
        '-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', (Join-Path $PSScriptRoot 'make.ps1'), 'devlocal-backend')
    try { DevLocalWeb }
    finally {
        # the backend and what it started (watchexec, cargo, goap-dev)
        if ($env:OS -eq 'Windows_NT') { & taskkill /T /F /PID $backend.Id 2>&1 | Out-Null }
        else { Stop-Process -Id $backend.Id -Force -ErrorAction SilentlyContinue }
    }
}

function DevLocalReset { Remove-Item -Recurse -Force .goap -ErrorAction SilentlyContinue }

function RunnerImage { Run docker build --build-arg SERVICE=goap-runner -t goap/runner:dev . }

function ClaudeAgentRunner { Toolchain; Run cargo run -q -p goap-cmd-connector-claude-coding-agent -- install }

# Engine socket for the docker-proxy service: Docker Desktop keeps it in its VM, at the default path
function DockerSock { if (-not $env:GOAP_DOCKER_SOCK) { $env:GOAP_DOCKER_SOCK = '/var/run/docker.sock' } }

function Up {
    RunnerImage
    DockerSock
    Run docker @Compose up --build -d
}

function Down { DockerSock; Run docker @Compose down }
function Logs { DockerSock; Run docker @Compose logs -f engine graph registry modelgw gateway }

function Help {
    @'
Usage: .\make.ps1 <target>   (or .\make.cmd <target>)

  toolchain         install rustup and the pinned Rust toolchain when missing (rust-toolchain.toml), check node
  watch-tool        install watchexec (devlocal's rebuild on change) when it is missing
  all               generate, build, test
  tools             install the development tools: watchexec, and buf when it is not on the PATH (npm)
  generate          regenerate the web's TypeScript (web/src/gen) from proto/, the catalogue of
                    operations and the form widget catalogue of the web
  build             cargo build of the workspace, the services copied into bin\
  test              cargo test of the workspace ($env:CARGO_EXCLUDE: e.g. --exclude <crate>)
  tidy              bring Cargo.lock in line with the manifests (cargo update --workspace)
  rs-build | rs-test | rs-lint   former names of build, test, lint
  web-test          unit tests of the web (needs npm install in web\)
  test-pg           every test, the PostgreSQL ones included (GOAP_TEST_PG_DSN, else a throw-away
                    pgvector container on PGTEST_PORT, 55432)
  lint              rustfmt + clippy -D warnings + Cargo.lock up to date + dsl.md sync check
  eval              offline evaluation cases of evals\ (or $env:EVAL) against a running gateway, as GOAP_TOKEN
  dev               single process, in-memory, demo data: http://localhost:8080
  devlocal          no docker: SQLite (.goap\goap.db), backend + IDE both reload on code change:
                    http://localhost:5173
  devlocal-backend  SQLite backend only, rebuilt and restarted by watchexec: http://localhost:8080
  devlocal-web      IDE only, hot-reloaded by vite, proxied to the backend: http://localhost:5173
  devlocal-reset    drop the local SQLite database
  web               same as devlocal-web
  runner-image      image of the script sandboxes (goap-runner)
  claude-agent-runner  install the Claude Agent SDK of the claude-coding-agent connector
                    (GOAP_CLAUDE_AGENT_DIR, default .goap\claude-agent; needs npm)
  up | down | logs  docker compose stack
'@ | Write-Host
}

switch ($Target) {
    'toolchain'        { Toolchain }
    'watch-tool'       { WatchTool }
    'rs-build'         { Build }
    'rs-test'          { Test }
    'rs-lint'          { Lint }
    'all'              { Generate; Build; Test }
    'tools'            { Tools }
    'generate'         { Generate }
    'build'            { Build }
    'test'             { Test }
    'tidy'             { Tidy }
    'web-test'         { WebTest }
    'test-pg'          { TestPg }
    'lint'             { Lint }
    'eval'             { Eval }
    'dev'              { Dev }
    'devlocal'         { DevLocal }
    'devlocal-backend' { DevLocalBackend }
    'devlocal-web'     { DevLocalWeb }
    'devlocal-reset'   { DevLocalReset }
    'web'              { DevLocalWeb }
    'runner-image'     { RunnerImage }
    'claude-agent-runner' { ClaudeAgentRunner }
    'up'               { Up }
    'down'             { Down }
    'logs'             { Logs }
    { $_ -in 'help', '-h', '--help' } { Help }
    default            { Help; throw "unknown target: $Target" }
}
