// Package bench is the load generator of the performance stack (make perf, deploy/compose/perf.yml): it writes nodes and
// versions through the graph service's API only (Connect RPCs, as a client of the platform would), on the two axes of
// the platform, the domain (what is changed: the types of a published domain, its versions, how many nodes) and the
// change (why: changes commit versions of those nodes), and measures every call. The measures are OpenTelemetry
// metrics (pushed to the collector, scraped by Prometheus, drawn by the Grafana dashboard of deploy/grafana) and a CSV
// of the progress (one row per window: totals and latencies), so a run can be charted without the stack too.
package bench

import (
	"fmt"
	"strings"
)

// Namespace is the namespace of the generated domain: the bench writes nowhere else.
const Namespace = "bench"

// LinkType is the link the created nodes carry to an earlier node.
const LinkType = Namespace + "@relates"

// DomainShape is the size of the generated domain (the domain axis): node types and attributes per type.
type DomainShape struct {
	Types      int // node types extending Item (T000, T001...)
	Attributes int // extra string attributes per type (a0, a1...), besides title, description, value and rev
}

// TypeName is the qualified name of the i-th generated node type.
func TypeName(i int) string { return fmt.Sprintf("%s@T%03d", Namespace, i) }

// DomainVersion is the version of the domain published at the given step (0: the first).
func DomainVersion(step int) string { return fmt.Sprintf("1.0.%d", step) }

// DomainYAML renders the definition of the bench domain at a publication step: version 1.0.<step>, the base type Item,
// the shape's types plus one per step (so each publication grows the domain) and the link type relates.
func DomainYAML(s DomainShape, step int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "name: %s\nversion: %s\ndescription: Generated by goap-bench, the load generator of the performance stack (step %d).\n", Namespace, DomainVersion(step), step)
	b.WriteString("nodeTypes:\n")
	b.WriteString("  - name: Item\n    description: Base of the generated types\n    attributes:\n")
	b.WriteString("      - {name: title, label: Title, type: string, asName: true}\n")
	b.WriteString("      - {name: description, label: Description, type: string, widget: textarea}\n")
	b.WriteString("      - {name: value, label: Value, type: number}\n")
	b.WriteString("      - {name: rev, label: Revision, type: number}\n")
	b.WriteString("    search: [{property: title, text: true}]\n")
	for i := 0; i < s.Types+step; i++ {
		fmt.Fprintf(&b, "  - name: T%03d\n    description: Generated type %d\n    extends: Item\n", i, i)
		if s.Attributes > 0 {
			b.WriteString("    attributes:\n")
			for a := 0; a < s.Attributes; a++ {
				fmt.Fprintf(&b, "      - {name: a%d, label: Attribute %d, type: string}\n", a, a)
			}
		}
	}
	b.WriteString("linkTypes:\n  - name: relates\n    description: A generated node relates to an earlier one\n    from: Item\n    to: Item\n    label: relates to\n    inverseLabel: related by\n")
	return b.String()
}
